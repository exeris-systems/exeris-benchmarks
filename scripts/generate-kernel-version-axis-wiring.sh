#!/usr/bin/env bash
# Generate the driver env files and target-asset-matrix entries for the kernel-version axis from
# runtime/drivers/kernel-version-axis-arms.json.
#
# These are generated rather than hand-written because the axis only means anything if each arm's
# (staged jar, JDK, preview flag) triple is exactly the one the manifest declares. Four of the eight
# arms share a single staged jar and are told apart ONLY by JDK and JVM flag, so a hand-edited env
# file that drifted by one token would silently produce two numbers for one configuration - and the
# comparative gate would pass, because nothing downstream re-derives the arm's identity.
#
# Two shapes in the emitted EXTERNAL_START_CMD are load-bearing and must not be "tidied up":
#
#   1. The JDK path is written UNQUOTED as ${ARM_JAVA_HOME}/bin/java. run-comparative.sh finds the
#      JVM by matching a token against (^|/)java$ and then records every flag between that token and
#      -jar as the run's JVM flags. Quoting the path makes the token end in java" instead of java,
#      the match fails, and the recorded flag list comes back empty - which would drop
#      --enable-preview from the reproducibility metadata of exactly the arms whose whole purpose is
#      that flag.
#   2. The -jar path is written LITERALLY, never through a variable. The harness pre-flight stats
#      the -jar argument without expanding shell variables, so a "$APP_JAR" there makes it look for
#      a file named literally $APP_JAR and rejects the target as misconfigured.
#
# Usage: scripts/generate-kernel-version-axis-wiring.sh [--check]
#          --check  verify the committed files match the manifest, write nothing (exit 1 on drift)

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

MANIFEST="runtime/drivers/kernel-version-axis-arms.json"
ENV_DIR="runtime/drivers/env"
MATRIX="runtime/drivers/target-asset-matrix.json"
PAIR_MANIFEST="scenarios/entity-read-by-id/comparative-pair-manifest.json"

CHECK_ONLY=0
[[ "${1:-}" == "--check" ]] && CHECK_ONLY=1

emit_env_file() {
  local target_id="$1" arm="$2" port="$3" jar="$4" group="$5" version="$6"
  local jdk_feature="$7" jdk_home_var="$8" preview="$9" app_release="${10}" role="${11}"

  local preview_token=""
  [[ "$preview" == "true" ]] && preview_token=" --enable-preview"

  local upper_id; upper_id="$(echo "$target_id" | tr 'a-z-' 'A-Z_')"

  cat <<EOF
# GENERATED by scripts/generate-kernel-version-axis-wiring.sh from
# runtime/drivers/kernel-version-axis-arms.json - do not edit by hand.
#
# Kernel-version axis, arm ${arm}: ${group}:${version} on JDK ${jdk_feature}
# (app compiled at release ${app_release}, preview flag ${preview}).
#
# ROLE: ${role}
#
# This arm is defined by the triple (staged jar, JDK, preview flag). Change any one of them here
# and the arm stops being the thing the axis claims to measure. Four arms share the staged jar
# ${jar##*/}
# and differ only by JDK and flag, so the jar path alone does not identify a run - which is why
# scripts/verify-kernel-version-axis-boot.sh re-derives all three from /proc at launch.

START_MODE=external
HEALTH_URL=http://localhost:${port}/health
HEALTH_TIMEOUT_SECONDS=60

# JDK homes are variables so the perf box can point at its own installs. The default is the
# developer-box layout. ${jdk_home_var} must be a JDK ${jdk_feature} or this arm is mislabelled.
${jdk_home_var}=\${${jdk_home_var}:-${!jdk_home_var:-/opt/jdk-${jdk_feature}}}
ARM_JAVA_HOME=\${${jdk_home_var}}

EXERIS_DB_JDBC_URL=\${EXERIS_DB_JDBC_URL:-jdbc:postgresql://localhost:5432/postgres?prepareThreshold=1}
EXERIS_DB_USERNAME=\${EXERIS_DB_USERNAME:-postgres}
EXERIS_DB_PASSWORD=\${EXERIS_DB_PASSWORD:-postgres}
EXERIS_DB_POOL_MIN_SIZE=\${EXERIS_DB_POOL_MIN_SIZE:-16}
EXERIS_DB_POOL_MAX_SIZE=\${EXERIS_DB_POOL_MAX_SIZE:-256}
${upper_id}_PORT=\${${upper_id}_PORT:-${port}}
SERVER_CPU_AFFINITY=\${SERVER_CPU_AFFINITY:-}
EXERIS_JAVA_OPTS="--add-opens java.base/sun.nio.ch=ALL-UNNAMED --add-opens java.base/java.io=ALL-UNNAMED --enable-native-access=ALL-UNNAMED\${EXERIS_JAVA_OPTS:+ \${EXERIS_JAVA_OPTS}}"
EXERIS_ENABLE_TELEMETRY_SUBSYSTEM=\${EXERIS_ENABLE_TELEMETRY_SUBSYSTEM:-false}
EXERIS_TELEMETRY_JFR_ENABLED=\${EXERIS_TELEMETRY_JFR_ENABLED:-\${EXERIS_ENABLE_TELEMETRY_SUBSYSTEM:-false}}
EXERIS_JFR_VTHREAD_PINNED=\${EXERIS_JFR_VTHREAD_PINNED:-false}
EXERIS_TRANSPORT_CERT_PATH=\${EXERIS_TRANSPORT_CERT_PATH:-}
EXERIS_TRANSPORT_KEY_PATH=\${EXERIS_TRANSPORT_KEY_PATH:-}
EXTERNAL_PID_FILE=\${EXTERNAL_PID_FILE:-/tmp/exeris-\${USER:-unknown}-${target_id}.pid}

EXTERNAL_START_CMD='EXERIS_PORT="\$${upper_id}_PORT" EXERIS_HTTP_MAX_VERSION="\${EXERIS_HTTP_MAX_VERSION:-HTTP_1_1}" EXERIS_HTTP_H2C_UPGRADE_ENABLED="\${EXERIS_HTTP_H2C_UPGRADE_ENABLED:-false}" EXERIS_TRANSPORT_CERT_PATH="\${EXERIS_TRANSPORT_CERT_PATH:-}" EXERIS_TRANSPORT_KEY_PATH="\${EXERIS_TRANSPORT_KEY_PATH:-}" EXERIS_DB_JDBC_URL="\$EXERIS_DB_JDBC_URL" EXERIS_DB_USERNAME="\$EXERIS_DB_USERNAME" EXERIS_DB_PASSWORD="\$EXERIS_DB_PASSWORD" EXERIS_DB_POOL_MIN_SIZE="\$EXERIS_DB_POOL_MIN_SIZE" EXERIS_DB_POOL_MAX_SIZE="\$EXERIS_DB_POOL_MAX_SIZE" EXERIS_ENABLE_TELEMETRY_SUBSYSTEM="\$EXERIS_ENABLE_TELEMETRY_SUBSYSTEM" EXERIS_TELEMETRY_JFR_ENABLED="\$EXERIS_TELEMETRY_JFR_ENABLED" EXERIS_JFR_VTHREAD_PINNED="\$EXERIS_JFR_VTHREAD_PINNED" \${TARGET_MEM_SCOPE_PREFIX:-}\${SERVER_CPU_AFFINITY:+taskset -c \${SERVER_CPU_AFFINITY} }\${ARM_JAVA_HOME}/bin/java \$EXERIS_JAVA_OPTS${preview_token} -jar ${jar} > /tmp/exeris-${target_id}-${port}.log 2>&1 & echo \$! > "\$EXTERNAL_PID_FILE"'
EXTERNAL_STOP_CMD='if [[ -f "\$EXTERNAL_PID_FILE" ]]; then pid="\$(cat "\$EXTERNAL_PID_FILE")"; kill "\$pid" >/dev/null 2>&1 || true; rm -f "\$EXTERNAL_PID_FILE"; fi'

TARGET_TIER=community
TARGET_PROTOCOL=h1
COMPARISON_AXIS=within-tier
EOF
}

# Defaults used only to seed the generated env files' fallback paths.
JDK25_HOME="${JDK25_HOME:-$HOME/.sdkman/candidates/java/25.0.3-tem}"
JDK26_HOME="${JDK26_HOME:-$HOME/.sdkman/candidates/java/26-oracle}"
JDK28_HOME="${JDK28_HOME:-$HOME/Pobrane/openjdk-28-ea+10_linux-x64_bin/jdk-28}"

drift=0
generated=0

while IFS=$'\t' read -r arm target_id port jar group version jdk_feature jdk_home_var preview app_release role; do
  [[ -n "$arm" ]] || continue
  out="${ENV_DIR}/${target_id}.env"
  tmp="$(mktemp)"
  emit_env_file "$target_id" "$arm" "$port" "$jar" "$group" "$version" \
                "$jdk_feature" "$jdk_home_var" "$preview" "$app_release" "$role" > "$tmp"

  if [[ $CHECK_ONLY -eq 1 ]]; then
    if [[ ! -f "$out" ]]; then
      echo "DRIFT: missing ${out}"; drift=1
    elif ! diff -q "$out" "$tmp" >/dev/null; then
      echo "DRIFT: ${out} differs from the manifest"; diff "$out" "$tmp" | head -12; drift=1
    fi
    rm -f "$tmp"
  else
    mv "$tmp" "$out"
    chmod 644 "$out"
    echo "wrote ${out}"
    generated=$((generated + 1))
  fi
done < <(python3 - "$MANIFEST" <<'PY'
import json, sys
for a in json.load(open(sys.argv[1]))["arms"]:
    print("\t".join([
        a["arm"], a["target_id"], str(a["port"]), a["staged_jar"],
        a["kernel_group_id"], a["kernel_version"], str(a["jdk_feature"]),
        a["jdk_home_var"], "true" if a["enable_preview_flag"] else "false",
        str(a["app_compiler_release"]), a["role"],
    ]))
PY
)

# --- target-asset-matrix entries -------------------------------------------------------------
python3 - "$MANIFEST" "$MATRIX" "$CHECK_ONLY" <<'PY'
import json, sys

manifest_path, matrix_path, check_only = sys.argv[1], sys.argv[2], sys.argv[3] == "1"
manifest = json.load(open(manifest_path))
matrix = json.load(open(matrix_path))

by_id = {t["target_id"]: t for t in matrix["targets"]}
changed = False

for a in manifest["arms"]:
    tid = a["target_id"]
    entry = {
        "target_id": tid,
        "tier": manifest["tier"],
        "protocol_mode": "h1",
        "launcher_mode": "external",
        "env_file": f"runtime/drivers/env/{tid}.env",
        "profile_id": tid,
        "compose_file": "",
        "jar_path": a["staged_jar"],
        "health_url": f"http://localhost:{a['port']}/health",
        "asset_state": "runnable",
        "eligibility_class": "baseline-candidate",
        "missing_assets": [],
        "non_runnable_reason": "",
        "descriptor": (
            f"Kernel-version axis arm {a['arm']}: {a['kernel_group_id']}:{a['kernel_version']} "
            f"on JDK {a['jdk_feature']}, app at release {a['app_compiler_release']}, "
            f"preview flag {'on' if a['enable_preview_flag'] else 'off'}"
        ),
        "app_dir": "targets/exeris-community-app",
        "eligibility_note": (
            "WITHIN-EXERIS kernel-version ladder only (see runtime/drivers/kernel-version-axis-arms.json). "
            "This arm is identified by the triple (staged jar, JDK, preview flag), not by the jar alone - "
            "four arms share one staged jar. It is NEVER a cross-runtime number: the ladder exists because "
            "the three kernel coordinates cannot share a JDK, so only the manifest's named legs are "
            "single-variable comparisons. Quoting any two arms that are not a declared leg mixes kernel "
            "version, JDK, and preview features in one number."
        ),
        "legacy_target_ids": [],
        "mode": "pure",
    }
    if tid in by_id:
        if by_id[tid] != entry:
            if check_only:
                print(f"DRIFT: matrix entry for {tid} differs from the manifest")
                sys.exit(1)
            by_id[tid].clear()
            by_id[tid].update(entry)
            changed = True
    else:
        if check_only:
            print(f"DRIFT: matrix has no entry for {tid}")
            sys.exit(1)
        matrix["targets"].append(entry)
        changed = True

if changed and not check_only:
    with open(matrix_path, "w") as fh:
        json.dump(matrix, fh, indent=2)
        fh.write("\n")
    print(f"updated {matrix_path}")
elif not check_only:
    print(f"{matrix_path} already current")
PY

# --- comparative pair manifest -----------------------------------------------------------------
# The scenario's pair manifest is what run-comparative.sh consults before it will run a pair at all.
# Registering only the declared legs there puts the ladder discipline inside the strict gate rather
# than only inside our campaign script, so an operator calling run-comparative.sh directly still
# cannot produce an undeclared cross-JDK number. The tempting headline pair (0.10.2 on JDK 26 vs the
# preview kernel on JDK 28) is registered as explicitly forbidden, with the reason attached.
python3 - "$MANIFEST" "$PAIR_MANIFEST" "$CHECK_ONLY" <<'PY'
import json, sys

axis_path, pair_path, check_only = sys.argv[1], sys.argv[2], sys.argv[3] == "1"
axis = json.load(open(axis_path))
pair = json.load(open(pair_path))

WORKLOAD_KEY = "entity-read-by-id-community-h1-loopback-runtime-wrk"
by_arm = {a["arm"]: a for a in axis["arms"]}

def target_entry(a):
    return {
        "target_id": a["target_id"],
        "tier": "community",
        "protocol_mode": "h1",
        "transport_mode": "loopback-h1",
        "maturity": "candidate",
        "claim_scope": "comparison_eligible",
        "notes": (
            f"Kernel-version ladder arm {a['arm']}: {a['kernel_group_id']}:{a['kernel_version']} on "
            f"JDK {a['jdk_feature']}, app at release {a['app_compiler_release']}, preview flag "
            f"{'on' if a['enable_preview_flag'] else 'off'}. Eligible ONLY inside the declared legs of "
            "runtime/drivers/kernel-version-axis-arms.json - the three kernel coordinates cannot share "
            "a JDK, so any other pairing moves kernel version, JDK and feature set at once."
        ),
    }

def pair_entry(leg):
    a, b = leg["leg"].split("->")
    ta, tb = by_arm[a]["target_id"], by_arm[b]["target_id"]
    return {
        "pair_id": f"{ta}__{tb}",
        "targets": [ta, tb],
        "tier": "community",
        "protocol_mode": "h1",
        "transport_mode": "loopback-h1",
        "workload_profile_key": WORKLOAD_KEY,
        "axis_note": (
            f"Kernel-version ladder leg {leg['leg']}. Isolates: {leg['isolates']}. "
            f"Held constant: {leg['held_constant']}. Claim: {leg['claim']}. "
            "Within-exeris ladder only - never a cross-runtime number."
        ),
    }

forbidden = {
    "reason": (
        "Kernel-version ladder end points: 0.10.2 is class-file major 70 with preview classes (JDK 26 "
        "only) and preview/0.11.0 is major 72 with preview classes (JDK 28 EA only), so this pair moves "
        "kernel version, JDK feature release and language/runtime feature set simultaneously and no part "
        "of the difference is attributable. Assemble this figure from the declared legs instead - see "
        "runtime/drivers/kernel-version-axis-arms.json."
    ),
    "targets": [by_arm["A"]["target_id"], by_arm["E"]["target_id"]],
}

changed = False
existing_targets = {t["target_id"]: t for t in pair["compatible_targets"]}
for a in axis["arms"]:
    want = target_entry(a)
    cur = existing_targets.get(a["target_id"])
    if cur != want:
        if check_only:
            print(f"DRIFT: pair-manifest compatible_targets entry for {a['target_id']}")
            sys.exit(1)
        if cur is None:
            pair["compatible_targets"].append(want)
        else:
            cur.clear(); cur.update(want)
        changed = True

existing_pairs = {p["pair_id"]: p for p in pair["allowed_pairs"]}
for leg in axis["legs"]:
    want = pair_entry(leg)
    cur = existing_pairs.get(want["pair_id"])
    if cur != want:
        if check_only:
            print(f"DRIFT: pair-manifest allowed_pairs entry for {want['pair_id']}")
            sys.exit(1)
        if cur is None:
            pair["allowed_pairs"].append(want)
        else:
            cur.clear(); cur.update(want)
        changed = True

if not any(f.get("targets") == forbidden["targets"] for f in pair["forbidden_pairs"]):
    if check_only:
        print("DRIFT: pair-manifest is missing the forbidden A-vs-E end-point pair")
        sys.exit(1)
    pair["forbidden_pairs"].append(forbidden)
    changed = True

if changed and not check_only:
    with open(pair_path, "w") as fh:
        json.dump(pair, fh, indent=2)
        fh.write("\n")
    print(f"updated {pair_path}")
elif not check_only:
    print(f"{pair_path} already current")
PY

if [[ $CHECK_ONLY -eq 1 ]]; then
  [[ $drift -eq 0 ]] || { echo "wiring has drifted from the manifest"; exit 1; }
  echo "wiring matches ${MANIFEST}"
else
  echo "generated ${generated} env file(s)"
fi
