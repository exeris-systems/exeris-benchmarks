#!/usr/bin/env bash
# provision-droplets.sh — Create the exeris-bench droplet pair on DigitalOcean:
#   exeris-bench-target   (target apps + Postgres/Neo4j/Axon; campaigns run here)
#   exeris-bench-loadgen  (k6/wrk/wrk2/h2load driver box)
# Both land in the same region and a dedicated VPC, so the driver reaches the
# target over the private subnet (10.x, free traffic, no public hop).
# Note the harness axis: campaign scripts are single-box (loopback) today;
# split-topology runs (driver on loadgen) carry a different transport_mode
# label and must never be mixed with loopback results. Either box can also
# act as a standalone single-box runner.
#
# Requires: doctl authenticated (DIGITALOCEAN_ACCESS_TOKEN or `doctl auth init`).
# Usage:
#   ./tools/cloud/do/provision-droplets.sh
#   DO_SIZE=c-8 DO_REGION=fra1 ./tools/cloud/do/provision-droplets.sh
set -euo pipefail

REGION="${DO_REGION:-fra1}"
IMAGE="${DO_IMAGE:-ubuntu-24-04-x64}"
TAG="exeris-bench"
KEY_NAME="exeris-bench"
PUBKEY="${DO_SSH_PUBKEY:-$HOME/.ssh/id_ed25519.pub}"
# Cost guard: pair must not exceed this hourly total (2 x c-8 = 0.50 USD/h).
MAX_HOURLY_TOTAL="${DO_MAX_HOURLY_TOTAL:-0.55}"
# Premium Intel CPU-Optimized first (same price as regular, NVMe + faster net),
# plain CPU-Optimized as fallback. Override with DO_SIZE.
SIZE_PREFERENCE=("c-8-intel" "c-8")

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_OUT="$SCRIPT_DIR/do-droplets.env"

# Resolve doctl binary (PATH, or the local install drop under ~/.local/bin).
DOCTL="${DOCTL:-}"
if [[ -z "$DOCTL" ]]; then
  for cand in doctl "$HOME/.local/bin/doctl" "$HOME/.local/bin/doctl.exe"; do
    if command -v "$cand" >/dev/null 2>&1; then DOCTL="$cand"; break; fi
  done
fi
[[ -n "$DOCTL" ]] || { echo "ERROR: doctl not found (set DOCTL=/path/to/doctl)" >&2; exit 1; }

echo "== Auth check =="
"$DOCTL" account get --format Email,Status,DropletLimit || {
  echo "ERROR: doctl is not authenticated. Set DIGITALOCEAN_ACCESS_TOKEN or run 'doctl auth init'." >&2
  exit 1
}

echo "== SSH key =="
[[ -f "$PUBKEY" ]] || { echo "ERROR: public key not found: $PUBKEY" >&2; exit 1; }
FP="$(ssh-keygen -lf "$PUBKEY" -E md5 | awk '{print $2}' | sed 's/^MD5://')"
if "$DOCTL" compute ssh-key list --format FingerPrint --no-header | grep -qF "$FP"; then
  echo "key already registered ($FP)"
else
  "$DOCTL" compute ssh-key import "$KEY_NAME" --public-key-file "$PUBKEY"
  echo "key imported ($FP)"
fi

echo "== Size selection =="
SIZE="${DO_SIZE:-}"
if [[ -z "$SIZE" ]]; then
  for cand in "${SIZE_PREFERENCE[@]}"; do
    if "$DOCTL" compute size list --format Slug --no-header | grep -qx "$cand"; then
      SIZE="$cand"; break
    fi
  done
fi
[[ -n "$SIZE" ]] || { echo "ERROR: no preferred size available; pass DO_SIZE=<slug>" >&2; exit 1; }
read -r VCPUS MEM PRICE_HOURLY < <("$DOCTL" compute size list --format Slug,VCPUs,Memory,PriceHourly --no-header \
  | awk -v s="$SIZE" '$1==s {print $2, $3, $4}')
[[ -n "${PRICE_HOURLY:-}" ]] || { echo "ERROR: size slug not found: $SIZE" >&2; exit 1; }
PAIR_HOURLY="$(awk -v p="$PRICE_HOURLY" 'BEGIN {printf "%.4f", 2*p}')"
echo "size=$SIZE (${VCPUS} vCPU / ${MEM} MB), pair cost = \$${PAIR_HOURLY}/h"
awk -v c="$PAIR_HOURLY" -v m="$MAX_HOURLY_TOTAL" 'BEGIN { exit (c <= m) ? 0 : 1 }' || {
  echo "ERROR: pair hourly \$${PAIR_HOURLY} exceeds guard \$${MAX_HOURLY_TOTAL} (override: DO_MAX_HOURLY_TOTAL)" >&2
  exit 1
}

echo "== VPC =="
VPC_UUID="$("$DOCTL" vpcs list --format ID,Name,Region --no-header \
  | awk -v r="$REGION" '$2=="exeris-bench" && $3==r {print $1; exit}')"
if [[ -z "$VPC_UUID" ]]; then
  VPC_UUID="$("$DOCTL" vpcs create --name exeris-bench --region "$REGION" --format ID --no-header)"
  echo "VPC created: $VPC_UUID"
else
  echo "VPC reused: $VPC_UUID"
fi

echo "== Droplets =="
EXISTING="$("$DOCTL" compute droplet list --format Name --no-header | grep -cE '^exeris-bench-(target|loadgen)$' || true)"
if [[ "$EXISTING" -gt 0 ]]; then
  echo "ERROR: exeris-bench droplet(s) already exist — destroy first (tools/cloud/do/destroy-droplets.sh --yes)" >&2
  exit 1
fi
"$DOCTL" compute droplet create exeris-bench-target exeris-bench-loadgen \
  --region "$REGION" \
  --size "$SIZE" \
  --image "$IMAGE" \
  --vpc-uuid "$VPC_UUID" \
  --ssh-keys "$FP" \
  --tag-name "$TAG" \
  --enable-monitoring \
  --wait

echo "== Addresses =="
LIST="$("$DOCTL" compute droplet list --tag-name "$TAG" --format Name,PublicIPv4,PrivateIPv4 --no-header)"
echo "$LIST"
TARGET_PUBLIC_IP="$(awk '$1=="exeris-bench-target" {print $2}' <<<"$LIST")"
TARGET_PRIVATE_IP="$(awk '$1=="exeris-bench-target" {print $3}' <<<"$LIST")"
LOADGEN_PUBLIC_IP="$(awk '$1=="exeris-bench-loadgen" {print $2}' <<<"$LIST")"
LOADGEN_PRIVATE_IP="$(awk '$1=="exeris-bench-loadgen" {print $3}' <<<"$LIST")"

cat > "$ENV_OUT" <<EOF
# Generated by provision-droplets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) — do not commit.
DO_REGION=$REGION
DO_SIZE=$SIZE
DO_PAIR_HOURLY_USD=$PAIR_HOURLY
TARGET_PUBLIC_IP=$TARGET_PUBLIC_IP
TARGET_PRIVATE_IP=$TARGET_PRIVATE_IP
LOADGEN_PUBLIC_IP=$LOADGEN_PUBLIC_IP
LOADGEN_PRIVATE_IP=$LOADGEN_PRIVATE_IP
EOF
echo "wrote $ENV_OUT"
echo
echo "Next steps (per droplet):"
echo "  ssh root@$TARGET_PUBLIC_IP 'bash -s' < tools/cloud/do/setup-droplet.sh"
echo "  ./tools/cloud/do/sync-repo.sh bench@$TARGET_PUBLIC_IP"
echo "  (same for exeris-bench-loadgen at $LOADGEN_PUBLIC_IP)"
echo
echo "Reminder: droplets bill per-second WHILE THEY EXIST (even powered off)."
echo "Destroy when done: ./tools/cloud/do/destroy-droplets.sh --yes"
